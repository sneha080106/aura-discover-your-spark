import { motion, useReducedMotion } from "motion/react";
/**
 * Scroll-reveal wrapper. Falls back to a plain, immediately visible element
 * when the user prefers reduced motion.
 */
export function Reveal({ children, delay = 0, y = 24, className }) {
  const reduced = useReducedMotion();
  if (reduced) return <div className={className}>{children}</div>;
  return (
    <motion.div
      className={className}
      initial={{
        opacity: 0,
        y,
      }}
      whileInView={{
        opacity: 1,
        y: 0,
      }}
      viewport={{
        once: true,
        amount: 0.25,
      }}
      transition={{
        duration: 0.7,
        delay,
        ease: [0.22, 1, 0.36, 1],
      }}
    >
      {children}
    </motion.div>
  );
}
